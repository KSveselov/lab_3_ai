def model_questions(model):
    regressor = model.named_steps["regressor"]
    if isinstance(regressor, DummyRegressor):
        return [
            ("Как работает E0 и зачем нужен?",
             "Всем рыбам предсказывается одна константа, вычисленная только на обучении. "
             "Среднее минимизирует сумму квадратов ошибок, медиана — сумму абсолютных ошибок на обучении. "
             "Это ориентир: полезная модель должна улучшать качество относительно простого постоянного прогноза. "
             "Размеры и вид на прогноз E0 не влияют.")]
    if isinstance(regressor, RandomForestRegressor):
        questions = [
            ("Как работает случайный лес?",
             "Каждое дерево обучается на выборке с возвращением и делит объекты по условиям признаков. "
             "В листе прогнозируется среднее масс обучающих объектов, итог леса — среднее прогнозов деревьев. "
             "Усреднение уменьшает разброс относительно отдельного глубокого дерева. "
             "Случайный выбор части признаков зависит от max_features; при доступности всех признаков его нет."),
            ("Что означают параметры леса и вычислительный бюджет?",
             "n_estimators — число деревьев; max_depth — максимальная глубина; min_samples_leaf — минимум "
             "обучающих наблюдений в каждом листе. В текущих E3/E4 сетка: 300 деревьев × глубины [None, 12] "
             "× минимум в листе [1, 2], то есть 4 кандидата × 5 фолдов + 1 refit = 21 обучение леса на версию. "
             "В E4 две версии: всего 42 обучения. n_jobs управляет параллельностью, а не числом обучений. "
             "Для архивного запуска без записи сетки этот бюджет нельзя считать подтверждённым."),
            ("Почему лес может быть полезнее линейной модели?",
             "Деревья описывают нелинейные зависимости и взаимодействия размеров. "
             "При положительных обучающих массах усреднение в листьях и между деревьями не даёт отрицательной массы. "
             "Лес плохо экстраполирует за диапазон обучающих масс; редкие виды и крупные рыбы представлены слабо."),
        ]
        if "Vproxy" in [c for _, _, cols in model.named_steps["preprocess"].transformers for c in cols]:
            questions.append(("Что проверяет E4-B?",
                              "Добавляется Vproxy = Length3 × Height × Width — приближение объёма. "
                              "Это не новая информация, а удобная форма взаимодействия размеров для модели. "
                              "Её сравнивают с E4-A на одинаковых строках, фолдах и сетке по CV MSE; "
                              "MAE, MSE и R² теста сообщают отдельно. Улучшение одного разбиения не доказывает устойчивый выигрыш."))
        else:
            questions.append(("Как связаны E3 и E4-A?",
                              "E4-A — контрольная версия с теми же базовыми признаками и сеткой, что E3. "
                              "E4 сравнивает её с добавлением Vproxy при одинаковом бюджете и разбиении."))
        return questions
    questions = [
        ("Как работает линейная модель?",
         "Прогноз — свободный член плюс сумма признаков, умноженных на коэффициенты. "
         "Она предполагает линейную связь в используемой шкале. Размеры рыбы могут быть взаимосвязаны "
         "(мультиколлинеарность), что делает отдельные коэффициенты нестабильными."),
        ("Какие коэффициенты сравнимы после согласованного масштабирования?",
         "Length3, Height и Width масштабируются StandardScaler: (x - среднее обучения) / стандартное отклонение обучения. "
         "Их коэффициенты относятся к изменению на одно стандартное отклонение при фиксированных остальных признаках. "
         "Индикаторы вида имеют другую интерпретацию; коэффициенты модели массы и модели логарифма массы напрямую несравнимы. "
         "Модуль коэффициента не является строгой мерой важности при связанных признаках. "
         "Для штрафа Ridge масштабирование не позволяет единицам измерения произвольно определять силу сжатия."),
        ("Как проверять остатки и неоднородность дисперсии?",
         "На графике остатков ищут кривизну, зоны одного знака и расширение разброса с массой или прогнозом. "
         "Расширение указывает на возможную гетероскедастичность; визуальный признак не заменяет формальный тест. "
         "Корреляции числовых признаков считают на обучении, устойчивость коэффициентов проверяют при повторных обучениях."),
    ]
    if isinstance(regressor, TransformedTargetRegressor):
        questions.append(("Что делает ln(1 + y) и как оценивать модель?",
                          "ln — натуральный логарифм. log1p сжимает большие массы и допускает y=0. "
                          "Модель обучается на z=ln(1+y), predict возвращает exp(z)-1 через expm1. "
                          "MAE и MSE считаются в граммах и г², R² безразмерен; CV тоже использует восстановленные прогнозы. "
                          "Логарифмируется только цель, не размеры. Обратное преобразование не гарантирует "
                          "несмещённую оценку средней массы или улучшение MSE; expm1 также может дать отрицательный прогноз при z<0."))
    elif isinstance(regressor, Ridge):
        questions.append(("Как выбирается регуляризация E2?",
                          "Используется L2: сумма квадратов ошибок + alpha × сумма квадратов коэффициентов. "
                          "Текущая сетка alpha=[0.01, 0.1, 1, 10, 100], 5 фолдов: 25 CV-обучений + 1 итоговое. "
                          "Выбор по минимальной средней CV MSE. Большой alpha сильнее уменьшает коэффициенты "
                          "и может привести к недообучению; отрицательные прогнозы Ridge не запрещает."))
    else:
        questions.append(("Почему E1 может предсказывать отрицательную массу?",
                          "Обычная линейная регрессия не ограничивает прогноз снизу. "
                          "Отрицательные массы — нарушение физического смысла, даже при хорошем общем R². "
                          "Округление не исправляет проблему; вариант log1p нужно оценивать отдельно."))
    return questions


def log_run_passport(run_id, model=None):
    """Добавляет документы через клиент, не меняя статус и метрики запуска."""
    client = mlflow.tracking.MlflowClient()
    run = client.get_run(run_id)
    if model is None:
        model = mlflow.sklearn.load_model(run.info.artifact_uri + "/model")
    regressor = model.named_steps["regressor"]
    questions = model_questions(model) + COMMON_QUESTIONS
    answers = ["# Вопросы и ответы для защиты", "", "Запуск: {}".format(run.info.run_name), ""]
    for question, answer in questions:
        answers.extend(["## " + question, "", answer, ""])
    passport = [
        "# Паспорт модели", "", "Модель: " + run.info.run_name,
        "Идентификатор запуска MLflow: " + run_id,
        "Задача: прогноз массы рыбы в граммах.",
        "Класс регрессора: " + type(regressor).__name__, "",
        "## Параметры конкретного запуска", "",
    ]
    for key, value in sorted(run.data.params.items()):
        passport.append("- {}: {}".format(key, value))
    passport.extend(["", "### Параметры сохранённого регрессора", ""])
    for key, value in sorted(regressor.get_params(deep=False).items()):
        passport.append("- `{}`: `{}`".format(key, value))
    passport.extend(["", "## Качество конкретного запуска", "",
                     "Метрики теста и CV относятся к исходной шкале массы: MAE — г, MSE — г², R² — безразмерный.", ""])
    for key in ("test_mae", "test_mse", "test_r2", "cv_mse_mean", "cv_mse_std",
                "error_negative_predictions", "error_non_finite_predictions"):
        title = {
            "test_mae": "Средняя абсолютная ошибка на тесте (MAE)",
            "test_mse": "Средняя квадратичная ошибка на тесте (MSE)",
            "test_r2": "Коэффициент детерминации на тесте (R²)",
        }.get(key, REPORT_LABELS[key])
        value = run.data.metrics.get(REPORT_LABELS[key])
        passport.append("- {}: {}".format(title, "не сохранено" if value is None else "{:.6f}".format(value)))
    passport.extend(["", "## Воспроизводимость", "",
                     "Предобработка и регрессор сохранены вместе в артефакте model/. "
                     "Для Vproxy перед вызовом Pipeline нужно вычислить произведение Length3 × Height × Width.", ""])
    for key in ("git_commit", "python_version", "mlflow_version", "sklearn_version"):
        label = REPORT_LABELS[key]
        passport.append("- {}: {}".format(label, run.data.tags.get(label, "не сохранено")))
    passport.extend(["", "## Анализ ошибок и ограничения", "",
                     "Таблицы прогнозов, остатков, ошибок по видам и размерам, пять крупнейших ошибок и графики "
                     "находятся в артефактах анализ_ошибок/. "
                     "Оценка ограничена составом текущего теста; для редких видов и размерных групп мало наблюдений. "
                     "Средняя CV MSE используется для выбора, тест — для итоговой оценки. "
                     "Сетка в ответах описывает текущий код; исторические параметры берутся из записей выше.", "",
                     "Причина ошибок: " + run.data.tags.get(REPORT_LABELS["error_analysis_diagnosis"], "см. анализ_ошибок/"),
                     "Следующий эксперимент: " + run.data.tags.get(REPORT_LABELS["next_experiment"], "см. анализ_ошибок/"), "",
                     "## Вопросы по модели и лабораторной", ""] + answers[4:])
    with TemporaryDirectory() as directory:
        for filename, lines in [("паспорт_модели.md", passport), ("вопросы_и_ответы.md", answers)]:
            path = Path(directory) / filename
            path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
            client.log_artifact(run_id, str(path), artifact_path="документация")
